// Writes the TypeScript type of identity's Principal contract from its JSON Schema, so a field the
// contract adds reaches the adapter mechanically. It knows the shapes the schema uses: strings (with
// an enum or as a date-time, kept as RFC 3339 text), booleans, arrays of strings, and objects.

interface Schema {
  title?: string
  description?: string
  type?: string
  format?: string
  enum?: string[]
  items?: Schema
  required?: string[]
  properties?: Record<string, Schema>
}

function doc(description: string | undefined, indent = ''): string {
  return description ? `${indent}/** ${description} */\n` : ''
}

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1)
}

function typeOf(name: string, field: Schema, types: string[]): string {
  if (field.enum) {
    const values = [...field.enum]
      .sort()
      .map((v) => `'${v}'`)
      .join(' | ')
    types.push(`${doc(field.description)}export type ${pascal(name)} = ${values}\n`)
    return pascal(name)
  }
  if (field.type === 'string' || field.type === 'boolean') return field.type
  if (field.type === 'array' && field.items?.type === 'string') return 'string[]'
  if (field.type === 'object') {
    types.push(objectType(pascal(name), field, types))
    return pascal(name)
  }
  throw new Error(`no TypeScript type for ${name} (type "${field.type}")`)
}

function objectType(name: string, schema: Schema, types: string[]): string {
  const required = new Set(schema.required ?? [])
  const fields = Object.entries(schema.properties ?? {})
    .map(
      ([field, s]) =>
        `${doc(s.description, '  ')}  ${field}${required.has(field) ? '' : '?'}: ${typeOf(field, s, types)}\n`,
    )
    .join('')
  return `${doc(schema.description)}export interface ${name} {\n${fields}}\n`
}

/** The TypeScript source of the Principal type, from the contract's schema. */
export function generate(schema: Schema): string {
  const types: string[] = []
  const principal = objectType(schema.title ?? 'Principal', schema, types)
  return [
    "// Generated by scripts/generate.ts from the Principal contract's schema; do not edit.\n",
    principal,
    ...types,
  ].join('\n')
}
